import { render, screen } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import TranscriptPage from '@/app/(student)/transcript/page';

const mocks = vi.hoisted(() => ({
  queryCollection: vi.fn(),
  profile: {} as Record<string, unknown>,
}));

vi.mock('@/hooks/useAuth', () => ({
  useAuth: () => ({ user: { uid: 'student-1', photoURL: null, getIdToken: vi.fn() }, loading: false }),
}));
vi.mock('@/hooks/useProfile', () => ({ useProfile: () => ({ profile: mocks.profile }) }));
vi.mock('@/lib/firebase/firestore', () => ({
  queryCollection: mocks.queryCollection,
  deleteDocument: vi.fn(),
  where: vi.fn(),
}));
vi.mock('@/components/cgpa/CGPAArc', () => ({ CGPAArc: () => <div data-testid="cgpa-arc" /> }));
vi.mock('react-hot-toast', () => ({ default: { error: vi.fn(), success: vi.fn(), loading: vi.fn() } }));

const semester = (gpa: number, creditLoaded: number, id = 'semester-1') => ({
  id, label: 'Year 3 — First Semester', session: '2025/2026', level: 300, semester: 1,
  gpa, pi: 3, creditLoaded, isComplete: true,
});

async function renderTranscript(semesters: ReturnType<typeof semester>[]) {
  // Answer by path so a late call from a previous test's render cannot take these semesters.
  mocks.queryCollection.mockImplementation(async (path: string) => (path.endsWith('/semesters') ? semesters : []));
  render(<TranscriptPage />);
  return screen.findByText('CUMULATIVE SUMMARY', {}, { timeout: 5000 });
}

const summaryLine = (label: string) => screen.getByText(label).closest('p') as HTMLElement;

describe('Student transcript record', () => {
  beforeEach(() => {
    mocks.queryCollection.mockReset();
    mocks.profile = { fullName: 'Ada Student', matric: 'AG/001', currentLevel: 300, department: 'Computer Science', programme: 'BSc', university: 'University of Lagos' };
  });
  afterEach(() => vi.restoreAllMocks());

  it('calls a 1.00-1.49 CGPA Pass, not Fail', async () => {
    await renderTranscript([semester(1.2, 18)]);
    expect(summaryLine('Projected Degree Class:')).toHaveTextContent('Projected Degree Class: Pass');
  });

  it('shows and classifies the same rounded CGPA at the 0.995 edge', async () => {
    await renderTranscript([semester(0.995, 1)]);
    expect(summaryLine('Cumulative CGPA:')).toHaveTextContent('Cumulative CGPA: 1.00 / 5.00');
    expect(summaryLine('Projected Degree Class:')).toHaveTextContent('Projected Degree Class: Pass');
  });

  it('keeps Fail below 1.00', async () => {
    await renderTranscript([semester(0.5, 18)]);
    expect(summaryLine('Projected Degree Class:')).toHaveTextContent('Projected Degree Class: Fail');
  });

  it('shows 539 points over 120 units as 4.49, Second Class Upper', async () => {
    await renderTranscript([semester(4.5, 40), semester(4.4875, 80, 'semester-2')]);
    expect(summaryLine('Cumulative CGPA:')).toHaveTextContent('Cumulative CGPA: 4.49 / 5.00');
    expect(summaryLine('Projected Degree Class:')).toHaveTextContent('Second Class Honours (Upper Division)');
  });

  it("heads the record with the student's own university and an unofficial-record heading", async () => {
    await renderTranscript([semester(4.2, 18)]);
    expect(screen.getByRole('heading', { name: 'University of Lagos' })).toBeInTheDocument();
    expect(screen.getByRole('heading', { name: 'Unofficial Academic Record — generated by AcadeGrade' })).toBeInTheDocument();
    expect(screen.getByText('Self-reported by the student. Not issued or verified by any university.')).toBeInTheDocument();
    expect(screen.queryByText(/Enugu State/i)).not.toBeInTheDocument();
    expect(screen.queryByText(/Agbani/i)).not.toBeInTheDocument();
  });

  it('says the university is not specified when the profile has none', async () => {
    mocks.profile = { ...mocks.profile, university: '  ' };
    await renderTranscript([semester(4.2, 18)]);
    expect(screen.getByRole('heading', { name: 'University not specified' })).toBeInTheDocument();
    expect(screen.queryByText(/Enugu State/i)).not.toBeInTheDocument();
  });
});
