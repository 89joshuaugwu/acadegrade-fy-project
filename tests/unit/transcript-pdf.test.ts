import { describe, expect, it } from 'vitest';
import { buildTranscript } from '@/lib/pdf/transcript';
import type { User } from '@/types/user';
import type { SemesterWithCourses } from '@/types/semester';

const student = (university: string) => ({
  fullName: 'Ada Student', matric: 'AG/001', currentLevel: 300, department: 'Computer Science', programme: 'BSc', university,
}) as unknown as User;

const semester = (gpa: number, creditLoaded: number, id = 'semester-1') => ({
  id, label: 'Year 3 — First Semester', session: '2025/2026', level: 300, semester: 1,
  gpa, pi: 3, creditLoaded, isComplete: true,
  courses: [{ id: 'c1', code: 'CSC 401', title: 'Compilers', units: 3, caScore: 20, examScore: 40, totalScore: 60, grade: 'B', gradePoint: 4, piPoint: 3, estimated: false }],
}) as unknown as SemesterWithCourses;

/** Text drawn on the PDF pages (jsPDF writes uncompressed "(text) Tj" operators). */
function pdfText(user: User, semesters: SemesterWithCourses[]) {
  const output = buildTranscript(user, semesters, null, { showPhoto: false }).output();
  return [...output.matchAll(/\((.*?)\) Tj/g)].map((match) => match[1].replace(/\\([()\\])/g, '$1'));
}

describe('PDF transcript', () => {
  it('calls a 1.00-1.49 CGPA Pass, not Fail', () => {
    expect(pdfText(student('University of Lagos'), [semester(1.2, 18)])).toContain('Pass');
  });

  it('shows and classifies the same rounded CGPA at the 0.995 edge', () => {
    const text = pdfText(student('University of Lagos'), [semester(0.995, 1)]);
    expect(text).toContain('Cumulative CGPA: 1.00 / 5.00');
    expect(text).toContain('Pass');
    expect(text).not.toContain('Fail');
  });

  it('shows 539 points over 120 units as 4.49, Second Class Upper', () => {
    const text = pdfText(student('University of Lagos'), [semester(4.5, 40), semester(4.4875, 80, 'semester-2')]);
    expect(text).toContain('Cumulative CGPA: 4.49 / 5.00');
    expect(text).toContain('Second Class Honours (Upper Division)');
  });

  it("heads every record with the student's own university, an unofficial-record heading and a per-page disclaimer", () => {
    const semesters = Array.from({ length: 6 }, (_, i) => semester(4.2, 18, `semester-${i}`));
    const text = pdfText(student('University of Lagos'), semesters);
    expect(text).toContain('University of Lagos');
    expect(text.some((line) => line.startsWith('Unofficial Academic Record') && line.endsWith('generated by AcadeGrade'))).toBe(true);
    const pages = text.filter((line) => /^Page \d+ of \d+$/.test(line)).length;
    expect(pages).toBeGreaterThan(1);
    expect(text.filter((line) => line === 'Self-reported by the student. Not issued or verified by any university.')).toHaveLength(pages);
    expect(text.join('\n')).not.toMatch(/ENUGU|AGBANI/i);
  });

  it('says the university is not specified when the profile has none', () => {
    const text = pdfText(student(''), [semester(4.2, 18)]);
    expect(text).toContain('University not specified');
    expect(text.join('\n')).not.toMatch(/ENUGU|AGBANI/i);
  });
});
