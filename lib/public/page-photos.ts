export type PhotoSlot = (typeof PHOTO_SLOTS)[number];

export interface PagePhoto {
  slot: PhotoSlot;
  /** Honest description of what the image shows. */
  alt: string;
  /** Optional short caption. */
  caption?: string;
  /** Id in lib/public/credits-data.ts for creditsFor() / <Credit ids>; null for the owner's own images. */
  creditId: string | null;
  /** CSS aspect ratio of the files, for example "4 / 5". */
  aspect: string;
  /** Fallback file for a plain <img>. */
  src: string;
  /** Pixel size of the largest file (width/height attributes). */
  width: number;
  height: number;
  /** width in px -> path, per format. Either map may be empty. */
  avif: Readonly<Record<number, string>>;
  webp: Readonly<Record<number, string>>;
  /** Ready-made srcset strings ("path 640w, path 1080w"); empty when the format is absent. */
  avifSrcSet: string;
  webpSrcSet: string;
  /** Point of interest, 0..1, and the matching CSS object-position. */
  focal: { x: number; y: number };
  objectPosition: string;
  /** First-screen image: load eagerly with fetchpriority="high". */
  priority: boolean;
}

