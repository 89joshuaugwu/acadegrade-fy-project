/**
 * Page images by slot name. Pages ask for a slot, never a file or a slug:
 * `photoFor('home.showcase')` returns a picture or null, and on null the section shows its
 * full-colour UiFrame, live slip or drawn stationery, which is the finished design.
 *
 * Owner decision 3 (20 Nov 2026): the owner's own generated images fill 12 slots (full colour,
 * untreated, no school names or signs; the people are illustrations and are never captioned as
 * AcadeGrade users). Files: /images/site/<image>/<width>.{avif,webp} (the PNG sources were removed after export).
 * Every other slot is null. creditId is null because the images are the owner's own; a later
 * third-party image would also need a non-withdrawn entry in lib/public/credits-data.ts.
 *
 * Self-contained on purpose (no import of the large credits registry), so client components can
 * use it.
 */

