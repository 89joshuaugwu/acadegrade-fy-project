/** The image for a slot, or null (show the section's interface or drawn picture). */
export function photoFor(slot: PhotoSlot): PagePhoto | null {
  const image = SLOT_IMAGES[slot];
  return image ? { ...image, slot } : null;
}

/** Credit ids for the given slots (deduplicated, in order), for a page's Credit line. Empty while every image is the owner's own. */
export function creditIdsFor(slots: readonly PhotoSlot[]): string[] {
  const ids: string[] = [];
  for (const slot of slots) {
    const id = SLOT_IMAGES[slot]?.creditId;
    if (id && !ids.includes(id)) ids.push(id);
  }
  return ids;
}
